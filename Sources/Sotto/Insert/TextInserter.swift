import AppKit
import ApplicationServices
import Carbon.HIToolbox

/// Types text into the focused app, then puts the user's clipboard back.
///
/// The usual path publishes the text as a lazy pasteboard promise and sends
/// Cmd+V, so we know when the target app has actually read it, and restores
/// the old clipboard only after that. A fixed delay can restore too early and
/// paste the old clipboard instead (Handy #502; the approach follows Handy
/// paste_tx).
///
/// If the app doesn't read the text within `readTimeout`, the promise is
/// withdrawn (so a late Cmd+V can't paste stale data) and the text goes in
/// another way: first through Accessibility, then as typed keystrokes if a
/// text field has focus, and as a last resort it's left on the clipboard for
/// the user to paste.
///
/// Insertions run one at a time. Overlapping ones used to share state, so a
/// quick second dictation could end the first one's wait early and paste
/// nothing or the old clipboard.
@MainActor
final class TextInserter: NSObject {
    enum Method: String {
        case paste, accessibility, typing
    }

    enum Outcome {
        case inserted(method: Method, chordAt: TimeInterval, landedAt: TimeInterval)
        /// No text field took it; the text is on the clipboard instead.
        case leftOnClipboard
        case failed
    }

    private static let readTimeout: Duration = .seconds(1)
    private static let ownMarker = NSPasteboard.PasteboardType("com.furkan.sotto.transcript")
    private static let markerTypes = [
        // Asks clipboard managers (Maccy, Paste) to skip the transcript.
        NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"),
        NSPasteboard.PasteboardType("org.nspasteboard.TransientType"),
        NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"),
        ownMarker,
    ]

    /// The promise currently on the pasteboard.
    private final class Attempt {
        let text: String
        var chordPosted = false
        var readAt: TimeInterval?
        var waiter: CheckedContinuation<Bool, Never>?
        init(text: String) { self.text = text }
    }

    private var attempt: Attempt?
    private var prepared: (snapshot: Snapshot, changeCount: Int, vKey: CGKeyCode)?
    private var busy = false
    private var queued: [CheckedContinuation<Void, Never>] = []

    /// Saves the clipboard and looks up the V key while the user is still
    /// talking, so neither happens after they let go. Skipped while an
    /// earlier insertion is still running, because the clipboard then holds
    /// that transcript, not the user's content.
    func prepare() {
        guard !busy else {
            prepared = nil
            return
        }
        let pasteboard = NSPasteboard.general
        prepared = (snapshot(pasteboard), pasteboard.changeCount, KeyLayout.keyCode(for: "v") ?? CGKeyCode(kVK_ANSI_V))
    }

    func insert(_ text: String) async -> Outcome {
        await acquire()
        defer { release() }

        let pasteboard = NSPasteboard.general
        var saved: Snapshot
        let vKey: CGKeyCode
        if let prepared, prepared.changeCount == pasteboard.changeCount {
            saved = prepared.snapshot
            vKey = prepared.vKey
        } else {
            // The user copied something while dictating; save that instead.
            saved = snapshot(pasteboard)
            vKey = KeyLayout.keyCode(for: "v") ?? CGKeyCode(kVK_ANSI_V)
        }
        prepared = nil
        if saved.contains(where: { $0[Self.ownMarker] != nil }) {
            // Never "restore" one of our own transcripts as the user's clipboard.
            saved = []
        }

        let attempt = Attempt(text: text)
        self.attempt = attempt
        defer { self.attempt = nil }

        pasteboard.clearContents()
        let item = NSPasteboardItem()
        item.setDataProvider(self, forTypes: [.string])
        for type in Self.markerTypes { item.setData(Data(), forType: type) }
        guard pasteboard.writeObjects([item]) else {
            restore(saved, to: pasteboard)
            return .failed
        }
        let promiseChange = pasteboard.changeCount

        guard postPaste(vKey: vKey) else {
            restore(saved, to: pasteboard)
            return .failed
        }
        let chordAt = ProcessInfo.processInfo.systemUptime
        attempt.chordPosted = true

        if await waitForRead(attempt, timeout: Self.readTimeout), let readAt = attempt.readAt {
            // Chromium-based apps read the pasteboard twice; give the second
            // read time before taking the text away (Handy paste_tx).
            try? await Task.sleep(for: .milliseconds(200))
            if pasteboard.changeCount == promiseChange { restore(saved, to: pasteboard) }
            return .inserted(method: .paste, chordAt: chordAt, landedAt: readAt)
        }

        // The app didn't take the paste. Withdraw the promise first, so a
        // late Cmd+V finds an empty clipboard rather than stale data.
        let app = NSWorkspace.shared.frontmostApplication?.localizedName ?? "unknown app"
        Log.app.notice("Paste not read by \(app, privacy: .public) within 1 s; trying fallbacks")
        if pasteboard.changeCount == promiseChange { pasteboard.clearContents() }
        let clearedChange = pasteboard.changeCount

        let outcome: Outcome
        if AccessibilityText.insert(text) {
            outcome = .inserted(method: .accessibility, chordAt: chordAt, landedAt: ProcessInfo.processInfo.systemUptime)
        } else if AccessibilityText.focusedFieldIsEditable(), await typeText(text) {
            outcome = .inserted(method: .typing, chordAt: chordAt, landedAt: ProcessInfo.processInfo.systemUptime)
        } else {
            // Nowhere to put it: leave it on the clipboard for the user.
            pasteboard.clearContents()
            pasteboard.setString(text, forType: .string)
            return .leftOnClipboard
        }
        // Give a slow app's late Cmd+V time to find the empty clipboard
        // before the user's content comes back.
        try? await Task.sleep(for: .seconds(1))
        if pasteboard.changeCount == clearedChange { restore(saved, to: pasteboard) }
        return outcome
    }

    /// Presses Return, or ⌘Return, to send a message. Only called after the
    /// text has landed, so Return never submits stale content (Handy paste_tx).
    func pressReturn(withCommand: Bool) {
        guard let source = CGEventSource(stateID: .hidSystemState),
              let down = CGEvent(keyboardEventSource: source, virtualKey: CGKeyCode(kVK_Return), keyDown: true),
              let up = CGEvent(keyboardEventSource: source, virtualKey: CGKeyCode(kVK_Return), keyDown: false)
        else { return }
        let flags: CGEventFlags = withCommand ? .maskCommand : []
        down.flags = flags
        up.flags = flags
        down.post(tap: .cghidEventTap)
        up.post(tap: .cghidEventTap)
    }

    // MARK: - One at a time

    private func acquire() async {
        guard busy else {
            busy = true
            return
        }
        await withCheckedContinuation { queued.append($0) }
    }

    private func release() {
        if queued.isEmpty {
            busy = false
        } else {
            queued.removeFirst().resume()
        }
    }

    // MARK: - Waiting for the read

    private func waitForRead(_ attempt: Attempt, timeout: Duration) async -> Bool {
        if attempt.readAt != nil { return true }
        return await withCheckedContinuation { continuation in
            attempt.waiter = continuation
            Task { @MainActor in
                try? await Task.sleep(for: timeout)
                Self.finish(attempt, read: false)
            }
        }
    }

    private static func finish(_ attempt: Attempt, read: Bool) {
        attempt.waiter?.resume(returning: read)
        attempt.waiter = nil
    }

    // MARK: - Keystrokes

    /// Cmd+V with the layout-aware V key. Command is released 100 ms later,
    /// without blocking, because some apps drop chords that end too fast
    /// (Handy #165).
    private func postPaste(vKey: CGKeyCode) -> Bool {
        guard let source = CGEventSource(stateID: .hidSystemState) else { return false }
        let commandKey = CGKeyCode(kVK_Command)
        guard let commandDown = CGEvent(keyboardEventSource: source, virtualKey: commandKey, keyDown: true),
              let vDown = CGEvent(keyboardEventSource: source, virtualKey: vKey, keyDown: true),
              let vUp = CGEvent(keyboardEventSource: source, virtualKey: vKey, keyDown: false),
              let commandUp = CGEvent(keyboardEventSource: source, virtualKey: commandKey, keyDown: false)
        else { return false }
        commandDown.flags = .maskCommand
        vDown.flags = .maskCommand
        vUp.flags = .maskCommand
        commandUp.flags = []
        commandDown.post(tap: .cghidEventTap)
        vDown.post(tap: .cghidEventTap)
        vUp.post(tap: .cghidEventTap)
        Task { @MainActor in
            try? await Task.sleep(for: .milliseconds(100))
            commandUp.post(tap: .cghidEventTap)
        }
        return true
    }

    /// Types the text as Unicode keystrokes, 20 characters per event (the
    /// most one event carries). Works in apps that ignore both the paste and
    /// Accessibility, such as some terminals and games.
    private func typeText(_ text: String) async -> Bool {
        guard let source = CGEventSource(stateID: .hidSystemState) else { return false }
        let units = Array(text.utf16)
        var index = 0
        while index < units.count {
            let chunk = Array(units[index..<min(index + 20, units.count)])
            guard let down = CGEvent(keyboardEventSource: source, virtualKey: 0, keyDown: true),
                  let up = CGEvent(keyboardEventSource: source, virtualKey: 0, keyDown: false)
            else { return false }
            down.flags = []
            up.flags = []
            down.keyboardSetUnicodeString(stringLength: chunk.count, unicodeString: chunk)
            up.keyboardSetUnicodeString(stringLength: chunk.count, unicodeString: chunk)
            down.post(tap: .cghidEventTap)
            up.post(tap: .cghidEventTap)
            index += 20
            // Electron apps drop keystrokes that arrive too fast.
            try? await Task.sleep(for: .milliseconds(4))
        }
        return true
    }

    // MARK: - Saving and restoring the user's clipboard

    private typealias Snapshot = [[NSPasteboard.PasteboardType: Data]]

    /// Every type of every item, so rich text and files survive too.
    private func snapshot(_ pasteboard: NSPasteboard) -> Snapshot {
        (pasteboard.pasteboardItems ?? []).map { item in
            item.types.reduce(into: [:]) { contents, type in
                if let data = item.data(forType: type) { contents[type] = data }
            }
        }
    }

    private func restore(_ saved: Snapshot, to pasteboard: NSPasteboard) {
        pasteboard.clearContents()
        let items = saved.map { contents in
            let item = NSPasteboardItem()
            for (type, data) in contents { item.setData(data, forType: type) }
            return item
        }
        if !items.isEmpty { pasteboard.writeObjects(items) }
    }
}

extension TextInserter: NSPasteboardItemDataProvider {
    /// AppKit calls this on the main thread when an app reads the promised text.
    nonisolated func pasteboard(_ pasteboard: NSPasteboard?, item: NSPasteboardItem, provideDataForType type: NSPasteboard.PasteboardType) {
        // The item never leaves the main thread; AppKit just doesn't say so.
        nonisolated(unsafe) let item = item
        MainActor.assumeIsolated {
            provide(item, type: type)
        }
    }

    private func provide(_ item: NSPasteboardItem, type: NSPasteboard.PasteboardType) {
        guard let attempt else { return }
        item.setString(attempt.text, forType: type)
        // Reads before Cmd+V come from clipboard managers, not the target app.
        guard attempt.chordPosted, attempt.readAt == nil else { return }
        attempt.readAt = ProcessInfo.processInfo.systemUptime
        Self.finish(attempt, read: true)
    }
}

/// Inserting text through the Accessibility API, the fallback when an app
/// ignores Cmd+V.
@MainActor
enum AccessibilityText {
    /// Replaces the selection in the focused text field with `text`, then
    /// checks that the field's value actually changed. Many apps report
    /// success without doing anything.
    static func insert(_ text: String) -> Bool {
        guard let element = focusedElement() else { return false }
        let before = value(of: element)
        guard AXUIElementSetAttributeValue(element, kAXSelectedTextAttribute as CFString, text as CFString) == .success else {
            return false
        }
        let after = value(of: element)
        return before != nil && after != nil && before != after
    }

    /// Whether something that takes text has keyboard focus. Typing into
    /// anything else could trigger the app's single-key shortcuts.
    static func focusedFieldIsEditable() -> Bool {
        guard let element = focusedElement() else { return false }
        var settable = DarwinBoolean(false)
        if AXUIElementIsAttributeSettable(element, kAXValueAttribute as CFString, &settable) == .success, settable.boolValue {
            return true
        }
        return AXUIElementIsAttributeSettable(element, kAXSelectedTextAttribute as CFString, &settable) == .success
            && settable.boolValue
    }

    private static func focusedElement() -> AXUIElement? {
        let system = AXUIElementCreateSystemWide()
        var focused: CFTypeRef?
        guard AXUIElementCopyAttributeValue(system, kAXFocusedUIElementAttribute as CFString, &focused) == .success,
              let focused, CFGetTypeID(focused) == AXUIElementGetTypeID()
        else { return nil }
        return (focused as! AXUIElement)
    }

    private static func value(of element: AXUIElement) -> String? {
        var value: CFTypeRef?
        guard AXUIElementCopyAttributeValue(element, kAXValueAttribute as CFString, &value) == .success else { return nil }
        return value as? String
    }
}
